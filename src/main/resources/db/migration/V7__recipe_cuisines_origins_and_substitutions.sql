CREATE TABLE ingredient_substitutions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recipe_ingredient_id BIGINT NOT NULL REFERENCES recipe_ingredients (id) ON DELETE CASCADE,
    substitute_ingredient_id BIGINT NOT NULL REFERENCES ingredients (id),
    amount NUMERIC(10, 3) NOT NULL CHECK (amount > 0),
    unit VARCHAR(30) NOT NULL CHECK (unit IN (
        'GRAM', 'KILOGRAM', 'MILLILITER', 'LITER', 'PIECE', 'TEASPOON',
        'TABLESPOON', 'PINCH', 'CLOVE', 'SLICE', 'BUNCH', 'PACKAGE'
    )),
    substitution_type VARCHAR(30) NOT NULL CHECK (substitution_type IN ('CLOSE', 'ADAPTED')),
    impact_note VARCHAR(1000) NOT NULL,
    sort_order INTEGER NOT NULL CHECK (sort_order > 0),
    UNIQUE (recipe_ingredient_id, substitute_ingredient_id),
    UNIQUE (recipe_ingredient_id, sort_order)
);

CREATE INDEX ingredient_substitutions_substitute_idx
    ON ingredient_substitutions (substitute_ingredient_id);
