CREATE TABLE ingredients (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(100) NOT NULL UNIQUE,
    name_ru VARCHAR(150) NOT NULL UNIQUE,
    name_en VARCHAR(150)
);

CREATE TABLE recipes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slug VARCHAR(120) NOT NULL UNIQUE,
    name_ru VARCHAR(200) NOT NULL,
    name_en VARCHAR(200),
    description TEXT NOT NULL,
    servings INTEGER NOT NULL CHECK (servings > 0),
    preparation_minutes INTEGER NOT NULL CHECK (preparation_minutes >= 0),
    cooking_minutes INTEGER NOT NULL CHECK (cooking_minutes >= 0),
    difficulty VARCHAR(20) NOT NULL CHECK (difficulty IN ('EASY', 'MEDIUM', 'HARD')),
    status VARCHAR(30) NOT NULL CHECK (status IN ('UNTESTED', 'TESTED', 'NEEDS_CHANGES', 'ARCHIVED')),
    source_name VARCHAR(300),
    source_url VARCHAR(1000),
    main_image_path VARCHAR(500),
    personal_notes TEXT,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE recipe_ingredients (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recipe_id BIGINT NOT NULL REFERENCES recipes (id) ON DELETE CASCADE,
    ingredient_id BIGINT NOT NULL REFERENCES ingredients (id),
    amount NUMERIC(10, 3) NOT NULL CHECK (amount > 0),
    unit VARCHAR(30) NOT NULL CHECK (unit IN (
        'GRAM', 'KILOGRAM', 'MILLILITER', 'LITER', 'PIECE', 'TEASPOON',
        'TABLESPOON', 'PINCH', 'CLOVE', 'SLICE', 'BUNCH', 'PACKAGE'
    )),
    optional BOOLEAN NOT NULL DEFAULT FALSE,
    sort_order INTEGER NOT NULL CHECK (sort_order > 0),
    UNIQUE (recipe_id, ingredient_id),
    UNIQUE (recipe_id, sort_order)
);

CREATE TABLE recipe_steps (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recipe_id BIGINT NOT NULL REFERENCES recipes (id) ON DELETE CASCADE,
    sort_order INTEGER NOT NULL CHECK (sort_order > 0),
    instruction TEXT NOT NULL,
    image_path VARCHAR(500),
    UNIQUE (recipe_id, sort_order)
);

CREATE TABLE equipment (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(100) NOT NULL UNIQUE,
    name_ru VARCHAR(150) NOT NULL UNIQUE,
    name_en VARCHAR(150)
);

CREATE TABLE cooking_methods (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(100) NOT NULL UNIQUE,
    name_ru VARCHAR(150) NOT NULL UNIQUE,
    name_en VARCHAR(150)
);

CREATE TABLE recipe_equipment (
    recipe_id BIGINT NOT NULL REFERENCES recipes (id) ON DELETE CASCADE,
    equipment_id BIGINT NOT NULL REFERENCES equipment (id),
    PRIMARY KEY (recipe_id, equipment_id)
);

CREATE TABLE recipe_cooking_methods (
    recipe_id BIGINT NOT NULL REFERENCES recipes (id) ON DELETE CASCADE,
    cooking_method_id BIGINT NOT NULL REFERENCES cooking_methods (id),
    PRIMARY KEY (recipe_id, cooking_method_id)
);

CREATE INDEX recipes_catalog_idx ON recipes (status, name_ru);
CREATE INDEX recipe_ingredients_ingredient_idx ON recipe_ingredients (ingredient_id);

